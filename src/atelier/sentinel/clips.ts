/** A copyable line, worded as it was found. */
export const clip = (id: string): Line => ({ kind: clips[id].kind, text: clips[id].text, clip: id })
export const copied = (s: State) => s.has.filter((f) => f.startsWith('clip:')).map((f) => f.slice(5))
export const cited = (s: State) => s.has.filter((f) => f.startsWith('cite:')).map((f) => f.slice(5))
/** Copying costs no time and cannot be undone. */
export const copy = (s: State, id: string): State => (has(s, `clip:${id}`) ? s : { ...s, has: [...s.has, `clip:${id}`] })
export function mark(s: State, id: string, m: State['marks'][string] | null): State {
  const marks = { ...s.marks }
  if (m) marks[id] = m
  else delete marks[id]
  return { ...s, marks }
}

